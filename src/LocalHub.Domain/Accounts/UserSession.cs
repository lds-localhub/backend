using LocalHub.Domain.Common;

namespace LocalHub.Domain.Accounts;

/// <summary>
/// A login session of a user. The JWT returned at login identifies this session.
/// </summary>
public class UserSession
{
    public static readonly TimeSpan Duration = TimeSpan.FromHours(8);

    // Used by Entity Framework; a session is created with Start.
    private UserSession() { }

    public int SessionId { get; private set; }
    public int UserId { get; private set; }
    public DateTimeOffset CreatedAt { get; private set; }
    public DateTimeOffset ExpiresAt { get; private set; }
    public DateTimeOffset? RevokedAt { get; private set; }

    // Navigation, loaded by Entity Framework with Include.
    public User User { get; private set; } = null!;

    public static UserSession Start(User user, DateTimeOffset now)
    {
        if (user.Status != ActivationStatus.Active)
        {
            throw new DomainException(DomainErrorKind.Forbidden, "A conta está desativada.");
        }

        // SessionId is generated by the database.
        return new UserSession
        {
            UserId = user.UserId,
            CreatedAt = now,
            ExpiresAt = now + Duration,
        };
    }

    public bool IsValid(DateTimeOffset now)
    {
        return RevokedAt == null && now < ExpiresAt;
    }

    public void Revoke(DateTimeOffset now)
    {
        // Keeps the first revocation date.
        if (RevokedAt == null)
        {
            RevokedAt = now;
        }
    }
}